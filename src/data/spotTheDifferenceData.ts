// Types for spot the difference game data
export interface Difference {
  x: number;
  y: number;
  radius: number;
}

export interface GameLevel {
  id: number;
  grade: number;
  imageA: string;
  imageB: string;
  differences: Difference[];
}

// Add scene types and difference arrays for cartoon scenes
export interface SceneConfig {
  sceneType: 'playground' | 'bedroom' | 'kitchen' | 'classroom' | 'toys' | 'garden';
  differencesA: string[]; // No differences for original image
  differencesB: string[]; // Differences for modified image
}

// Enhanced game level with cartoon scene configuration
export interface GameLevelWithScene extends GameLevel {
  sceneConfig?: SceneConfig;
  useCartoonScene: boolean;
}

